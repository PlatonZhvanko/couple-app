    static func phrases(for cat: Cat, topic: CatTopic) -> [String] {
        if let list = table["\(cat.rawValue).\(topic.rawValue)"], !list.isEmpty {
            return list
        }
        return table["\(cat.rawValue).greeting"] ?? ["Мяу!"]
    }

    /// Случайная реплика; одна и та же подряд не выпадает.
    static func random(for cat: Cat, topic: CatTopic) -> String {
        let list = phrases(for: cat, topic: topic)
        let key = "cat.lastPhrase.\(cat.rawValue).\(topic.rawValue)"
        let last = UserDefaults.standard.integer(forKey: key) - 1
        var index = Int.random(in: 0..<list.count)
        if list.count > 1 && index == last {
            index = (index + 1) % list.count
        }
        UserDefaults.standard.set(index + 1, forKey: key)
        return list[index]
    }
