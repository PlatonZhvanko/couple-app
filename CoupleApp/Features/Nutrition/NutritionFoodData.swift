    /// Разобранная база. Считается один раз.
    static let foods: [NutritionCatalogItem] = {
        raw.split(separator: "\n").compactMap { line -> NutritionCatalogItem? in
            let parts = line.split(separator: "|", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count >= 7,
                  let kcal = Double(parts[3]), let protein = Double(parts[4]),
                  let fat = Double(parts[5]), let carbs = Double(parts[6]) else { return nil }
            let piece = parts.count > 7 ? (Double(parts[7]) ?? 0) : 0
            let values = NutritionFoodValues(
                name: parts[0], brand: parts[1], kcal: kcal, protein: protein, fat: fat,
                carbs: carbs, pieceGrams: piece, defaultGrams: piece > 0 ? piece : 100
            )
            return NutritionCatalogItem(category: parts[2], values: values)
        }
    }()

    static let categories: [String] = {
        var seen: [String] = []
        for item in foods where !seen.contains(item.category) { seen.append(item.category) }
        return seen
    }()

    /// Найти продукт по названию без учёта регистра (для рецептов).
    static func find(_ name: String) -> NutritionFoodValues? {
        let key = name.lowercased()
        return foods.first { $0.values.name.lowercased() == key }?.values
    }
